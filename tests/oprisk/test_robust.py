"""S-3: the optimally bias-robust (OBRE) and Cramer-von Mises severity fits and the mean-adjusted SLA.

Known truth: a left-truncated lognormal generated by the inverse of its truncated cdf, with and without a share of gross
losses; closed forms for the Cramer-von Mises statistic and the mean adjustment.
"""

from __future__ import annotations

import dataclasses
import math

import numpy as np
import pytest
from scipy import stats

from riskvalidation.oprisk import distributions, robust, sla

H = 20_000.0
TRUE = (10.0, 1.6)  # log-scale mu, sigma of the lognormal before truncation (EUR)


def _sample(n: int, seed: int, law: str = "lognormal", params=TRUE, h: float = H) -> np.ndarray:
    rng = np.random.default_rng(seed)
    f_h = float(distributions.severity_cdf(law, params, np.array([h]))[0])
    u = f_h + rng.random(n) * (1.0 - f_h)
    return distributions.severity_ppf(law, params, u)


def _contaminate(x: np.ndarray, share: float, factor: float, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    y = x.copy()
    idx = rng.choice(x.size, size=int(round(share * x.size)), replace=False)
    y[idx] = y[idx] * factor
    return y


# ----------------------------------------------------------------------------------------------------------------
# mean-adjusted SLA


def test_mean_adjusted_sla_closed_form_gpd():
    law, params = "gpd", (0.5, 100.0, 0.0)  # mean = beta / (1 - xi) = 200
    r = robust.sla_var_mean_adjusted(10.0, law, params, 0.99)
    assert r.var_first_order == pytest.approx(sla.sla_var(10.0, law, params, 0.99), rel=1e-14)
    assert r.mean_adjustment == pytest.approx((10.0 - 1.0) * 200.0, rel=1e-13)
    assert r.var == pytest.approx(r.var_first_order + 1800.0, rel=1e-13)
    assert r.frequency_mean == 10.0 and r.level == 0.99
    assert r.status == "SECONDARY_SOURCE"


def test_mean_adjusted_sla_lognormal_and_difference_to_the_unverified_form():
    r = robust.sla_var_mean_adjusted(41.0, "lognormal", (10.0, 1.6), 0.999)
    mean = math.exp(10.0 + 0.5 * 1.6 ** 2)
    assert r.mean_adjustment == pytest.approx(40.0 * mean, rel=1e-13)
    old = sla.sla_var_mean_corrected(41.0, "lognormal", (10.0, 1.6), 0.999)
    assert old.var - r.var == pytest.approx(mean, rel=1e-12)  # E[N] E[X] versus (E[N] - 1) E[X]
    assert dataclasses.is_dataclass(r)
    with pytest.raises(dataclasses.FrozenInstanceError):
        r.var = 0.0  # type: ignore[misc]


def test_mean_adjusted_sla_refusals():
    with pytest.raises(ValueError, match="infinite mean"):
        robust.sla_var_mean_adjusted(10.0, "gpd", (1.2, 100.0, 0.0), 0.999)
    with pytest.raises(ValueError):
        robust.sla_var_mean_adjusted(0.5, "lognormal", (10.0, 1.0), 0.999)  # E[N] below 1: no adjustment exists
    with pytest.raises(ValueError):
        robust.sla_var_mean_adjusted(10.0, "lognormal", (10.0, 1.0), 1.0)
    with pytest.raises(ValueError):
        robust.sla_var_mean_adjusted(float("nan"), "lognormal", (10.0, 1.0), 0.99)


