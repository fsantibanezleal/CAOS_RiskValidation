# OBRE


def test_obre_clean_data_near_the_truncated_mle():
    x = _sample(3000, 21)
    mle = distributions.fit_severity("lognormal", x, H, truncated=True)
    fit = robust.fit_severity_obre("lognormal", x, H, efficiency=0.95)
    assert fit.method == "obre" and fit.converged and fit.weights.shape == (3000,)
    assert fit.params[0] == pytest.approx(mle.params[0], abs=0.15)
    assert fit.params[1] == pytest.approx(mle.params[1], rel=0.06)
    assert fit.bound > math.sqrt(2.0)
    assert np.all(fit.weights > 0.0) and np.all(fit.weights <= 1.0)


def test_obre_efficiency_one_limit_is_the_mle():
    x = _sample(1500, 22)
    mle = distributions.fit_severity("lognormal", x, H, truncated=True)
    fit = robust.fit_severity_obre("lognormal", x, H, efficiency=0.999)
    assert fit.params[0] == pytest.approx(mle.params[0], abs=0.03)
    assert fit.params[1] == pytest.approx(mle.params[1], rel=0.02)


def test_obre_resists_gross_losses_where_the_mle_does_not():
    x = _sample(1000, 31)
    y = _contaminate(x, 0.04, 400.0, 5)
    mle = distributions.fit_severity("lognormal", y, H, truncated=True)
    fit = robust.fit_severity_obre("lognormal", y, H)
    err_mle = abs(mle.params[1] - TRUE[1])
    err_obre = abs(fit.params[1] - TRUE[1])
    assert err_mle > 0.3
    assert err_obre < 0.5 * err_mle
    # the gross losses carry the smallest weights
    worst = np.argsort(fit.weights)[:40]
    changed = np.flatnonzero(y != x)
    assert len(set(worst.tolist()) & set(changed.tolist())) >= 30


def test_cvm_also_breaks_less_than_the_mle():
    x = _sample(1000, 31)
    y = _contaminate(x, 0.04, 400.0, 5)
    mle = distributions.fit_severity("lognormal", y, H, truncated=True)
    fit = robust.fit_severity_cvm("lognormal", y, H)
    assert abs(fit.params[1] - TRUE[1]) < abs(mle.params[1] - TRUE[1])


def test_obre_weibull_and_gpd_run_on_clean_data():
    xw = _sample(2000, 41, "weibull", (0.8, 50_000.0), 5_000.0)
    fw = robust.fit_severity_obre("weibull", xw, 5_000.0)
    assert fw.converged and fw.params[0] == pytest.approx(0.8, rel=0.12)
    xg = _sample(2000, 42, "gpd", (0.3, 30_000.0, H), H)
    fg = robust.fit_severity_obre("gpd", xg, H)
    assert fg.converged and fg.params[0] == pytest.approx(0.3, abs=0.15) and fg.params[2] == H


def test_obre_validation():
    x = _sample(200, 3)
    for eff in (0.4, 1.0, float("nan")):
        with pytest.raises(ValueError):
            robust.fit_severity_obre("lognormal", x, H, efficiency=eff)
    with pytest.raises(ValueError):
        robust.fit_severity_obre("lognormal", x[:5], H)
    with pytest.raises(ValueError, match="below the collection threshold"):
        robust.fit_severity_obre("lognormal", np.append(x, 1.0), H)
    a, b = robust.fit_severity_obre("lognormal", x, H), robust.fit_severity_obre("lognormal", x, H)
    assert a.params == b.params


def test_capital_chain_runs_end_to_end():
    x = _sample(500, 51)
    fit = robust.fit_severity_obre("lognormal", x, H)
    lam = distributions.rescale_frequency(41.0, "lognormal", fit.params, H)
    r = robust.sla_var_mean_adjusted(lam, "lognormal", fit.params, 0.999)
    assert r.var > r.var_first_order > 0.0


def test_obre_achieves_the_requested_efficiency():
    x = _sample(800, 61)
    for eff in (0.80, 0.95):
        fit = robust.fit_severity_obre("lognormal", x, H, efficiency=eff)
        assert fit.efficiency == pytest.approx(eff, abs=0.01)
    assert robust.fit_severity_obre("lognormal", x, H, efficiency=0.80).bound < fit.bound


def test_the_study_script_runs_a_small_history_set_and_the_truth_is_unbiased_for_the_known_law():
    import importlib.util
    from pathlib import Path

    path = Path(__file__).resolve().parents[2] / "scripts" / "oprisk_robust_study.py"
    if not path.exists():
        pytest.skip("the scripts folder is not in the tree this test runs from")
    spec = importlib.util.spec_from_file_location("oprisk_robust_study", path)
    study = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(study)
    res = study.run("lognormal", 12, 7, n=300)
    assert set(res["methods"]) == set(study.METHODS)
    # clean data from the assumed family: the maximum likelihood capital ratio is centred near 1
    assert 0.5 < res["methods"]["mle-lognormal"]["median_ratio"] < 2.0
    assert res["methods"]["obre"]["n_defined"] == 12
    assert res == study.run("lognormal", 12, 7, n=300)  # deterministic under the seed
    with pytest.raises(ValueError):
        study.run("nope", 2, 1)
