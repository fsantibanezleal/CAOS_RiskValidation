# Cramer-von Mises


def test_cvm_statistic_closed_form():
    # one observation at the median of an untruncated lognormal: W2 = 1/12 + (0.5 - 0.5)^2 = 1/12
    x = np.array([math.exp(1.0)])
    assert robust.cramer_von_mises_distance("lognormal", (1.0, 0.5), x) == pytest.approx(1.0 / 12.0, rel=1e-12)
    # two observations at the quartiles: 1/24 + 0
    q = stats.lognorm.ppf([0.25, 0.75], 0.5, scale=math.e)
    assert robust.cramer_von_mises_distance("lognormal", (1.0, 0.5), q) == pytest.approx(1.0 / 24.0, rel=1e-10)
    # the truncated form uses (F(x) - F(H)) / (1 - F(H))
    xs = _sample(300, 1)
    w = robust.cramer_von_mises_distance("lognormal", TRUE, xs, collection_threshold=H)
    u = np.sort(distributions.truncated_severity_cdf("lognormal", TRUE, xs, H))
    n = xs.size
    expect = 1.0 / (12 * n) + float(np.sum((u - (2 * np.arange(1, n + 1) - 1) / (2 * n)) ** 2))
    assert w == pytest.approx(expect, rel=1e-12)


def test_cvm_recovers_truth_and_beats_truth_in_distance():
    x = _sample(4000, 7)
    fit = robust.fit_severity_cvm("lognormal", x, H)
    assert fit.method == "cvm" and fit.converged and fit.n == 4000 and fit.threshold == H
    assert fit.params[0] == pytest.approx(TRUE[0], abs=0.15)
    assert fit.params[1] == pytest.approx(TRUE[1], rel=0.05)
    assert fit.statistic <= robust.cramer_von_mises_distance("lognormal", TRUE, x, H) + 1e-12
    assert math.isnan(fit.bound) and fit.weights.size == 0


def test_cvm_is_deterministic_and_validates():
    x = _sample(200, 3)
    a, b = robust.fit_severity_cvm("lognormal", x, H), robust.fit_severity_cvm("lognormal", x, H)
    assert a.params == b.params
    with pytest.raises(ValueError, match="below the collection threshold"):
        robust.fit_severity_cvm("lognormal", np.append(x, 5.0), H)
    with pytest.raises(ValueError):
        robust.fit_severity_cvm("lognormal-gpd-splice", x, H)
    with pytest.raises(ValueError):
        robust.fit_severity_cvm("lognormal", x[:2], H)
    with pytest.raises(ValueError):
        robust.fit_severity_cvm("lognormal", np.append(x, np.nan), H)


def test_cvm_weibull_and_gpd_recover_truth():
    xw = _sample(3000, 11, "weibull", (0.8, 50_000.0), 5_000.0)
    fw = robust.fit_severity_cvm("weibull", xw, 5_000.0)
    assert fw.params[0] == pytest.approx(0.8, rel=0.08) and fw.params[1] == pytest.approx(50_000.0, rel=0.15)
    xg = _sample(3000, 12, "gpd", (0.4, 30_000.0, H), H)
    fg = robust.fit_severity_cvm("gpd", xg, H)
    assert fg.params[0] == pytest.approx(0.4, abs=0.12) and fg.params[1] == pytest.approx(30_000.0, rel=0.2)
    assert fg.params[2] == H


