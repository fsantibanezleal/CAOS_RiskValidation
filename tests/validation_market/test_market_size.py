"""RV-827: the size of every back-test on simulated correct forecasts, within the Monte Carlo error of the replications.

The rejection rate at the red level (`alpha_red = 0.05`, one-sided where the test is one-sided) of a back-test that is
run on data generated by the forecast model itself must be about 5 percent."""

from __future__ import annotations

import json
import os

import numpy as np
import pytest
from scipy import stats

from riskvalidation.core.result import Light
from riskvalidation.generators.size_studies import STUDIES, study
from riskvalidation.market import frtb
from riskvalidation.validation import market as m
from size_kit import ROOT, page_paragraph

_RECORD: dict = {}


def rate(flags):
    return float(np.mean(flags))


def record(name, flags):
    """The rejection rate of a back-test on correct forecasts, stored (and written to MARKET_SIZE_OUT, a path) so that
    the sizes of two runs can be compared exactly."""
    _RECORD[name] = {"rate": rate(flags), "n": len(flags)}
    out = os.environ.get("MARKET_SIZE_OUT")
    if out:
        with open(out, "w", encoding="utf-8") as fh:
            json.dump(_RECORD, fh, indent=1, sort_keys=True)
    return flags


def check_size(flags, nominal=0.05, k=3.6, slack=0.0):
    r = rate(flags)
    se = np.sqrt(nominal * (1 - nominal) / len(flags))
    assert abs(r - nominal) <= k * se + slack, f"rejection rate {r:.4f} vs {nominal} (se {se:.4f}, n {len(flags)})"


PAGE = ROOT / "docs" / "market" / "07_backtests.md"


def _shared(*ids, index=0):
    """The studies of tests that are read on one stream of one null scenario (`generators.size_studies`)."""
    studies = [study(tid, index) for tid in ids]
    first = studies[0]
    assert all(s.null == first.null and s.seed == first.seed and s.n_rep == first.n_rep for s in studies)
    return first, studies


def _on_page(tid, label, flags):
    """The page states the size this suite measured (the figures come from the run, never typed)."""
    st = next(s for s in STUDIES[tid] if s.label == label)
    assert f"{100 * rate(flags):.2f}%" in page_paragraph(PAGE, st), (tid, label, "the page must state the size")


def test_size_of_the_var_backtests():
    first, (kup_s, ind_s, cc_s, dq_s) = _shared("market.kupiec_pof", "market.christoffersen_independence",
                                                "market.christoffersen_conditional_coverage",
                                                "market.dynamic_quantile_test")
    rng = np.random.default_rng(first.seed)
    alpha, reps = first.null.alpha, first.n_rep
    kup, ind, cc, dq = [], [], [], []
    for _ in range(reps):
        d = first.null.draw(rng)
        hits = d["hits"]
        kup.append(m.kupiec_pof(hits, alpha).light is Light.RED)
        ind.append(m.christoffersen_independence(hits, alpha).light is Light.RED)
        cc.append(m.christoffersen_conditional_coverage(hits, alpha).light is Light.RED)
        dq.append(m.dynamic_quantile_test(hits, d["var"], alpha, seed=len(dq), **dq_s.test_kwargs).p_value <= 0.05)
    # the asymptotic laws are close to exact at 75 expected exceedances; allow 0.01 for the approximation
    for name, st, flags in (("kupiec_pof", kup_s, kup), ("christoffersen_independence", ind_s, ind),
                            ("christoffersen_conditional_coverage", cc_s, cc), ("dynamic_quantile_test", dq_s, dq)):
        check_size(record(name, flags), slack=0.01)
        _on_page(st.test_id, st.label, flags)


def test_size_of_the_dq_test_at_production_configurations():
    """Review M1: the asymptotic chi-square DQ rejected correct forecasts 9.9 percent at (alpha 0.01, T 250), 8.2
    percent at (0.025, 250) and 14.3 percent at (0.01, 750); the light now follows a Monte Carlo p-value, which is
    exact in size."""
    configs = STUDIES["market.dynamic_quantile_test"][1:]
    assert len({s.seed for s in configs}) == 1   # the three configurations are read on one stream, in this order
    rng = np.random.default_rng(configs[0].seed)
    for st in configs:
        alpha = st.null.alpha
        flags = []
        for i in range(st.n_rep):       # the contract asks for at least 2000 replications and a rate in [0.03, 0.07]
            d = st.null.draw(rng)
            r = m.dynamic_quantile_test(d["hits"], d["var"], alpha, seed=i, **st.test_kwargs)
            flags.append(r.p_value <= 0.05)
        record(f"dynamic_quantile_test at alpha {alpha}, T {st.null.t}", flags)
        _on_page(st.test_id, st.label, flags)
        assert st.n_rep >= 2000 and 0.03 <= rate(flags) <= 0.07, (alpha, st.null.t, rate(flags))


def test_size_of_the_duration_test():
    st = study("market.duration_test")
    rng = np.random.default_rng(st.seed)
    alpha = st.null.alpha
    flags = []
    for i in range(st.n_rep):
        hits = st.null.draw(rng)["hits"]
        r = m.duration_test(hits, alpha, seed=i, **st.test_kwargs)
        flags.append(r.p_value <= 0.05)  # the Monte Carlo p-value is (1 + k) / 100, so 0.05 is the nominal cut
    check_size(record("duration_test", flags), slack=0.01)
    _on_page(st.test_id, st.label, flags)


def test_size_of_the_es_backtests():
    ac, du, dc = study("market.acerbi_szekely"), study("market.du_escanciano_unconditional"), study(
        "market.du_escanciano_conditional")
    assert ac.seed == du.seed == dc.seed and du.null == dc.null  # one stream, in this order
    rng = np.random.default_rng(ac.seed)
    # Acerbi and Szekely Z2 with simulated critical values, normal losses, T = 250, alpha = 2.5 percent
    flags = []
    for i in range(ac.n_rep):
        d = ac.null.draw(rng)
        r = m.acerbi_szekely(d["loss"], d["var"], d["es"], d["alpha"], d["simulate_null"], seed=i, **ac.test_kwargs)
        flags.append(r.p_value <= 0.05)
    check_size(record("acerbi_szekely", flags), slack=0.015)
    _on_page(ac.test_id, ac.label, flags)
    # Du and Escanciano on uniform PITs
    uncond, cond = [], []
    for _ in range(du.n_rep):
        d = du.null.draw(rng)
        uncond.append(m.du_escanciano_unconditional(d["pit"], d["alpha"]).p_value < 0.05)
        cond.append(m.du_escanciano_conditional(d["pit"], d["alpha"], **dc.test_kwargs).p_value < 0.05)
    check_size(record("du_escanciano_unconditional", uncond), slack=0.012)
    check_size(record("du_escanciano_conditional", cond), slack=0.012)
    _on_page(du.test_id, du.label, uncond)
    _on_page(dc.test_id, dc.label, cond)
    # McNeil and Frey on normal losses with the true VaR and ES: the exceedance residuals have mean zero. Its own
    # size study is tests/validation_market/test_market_mcneil_frey_size_power.py; this check keeps the CI band
    a3, t3 = 0.05, 1200
    z3 = stats.norm.ppf(1 - a3)
    es3 = stats.norm.pdf(z3) / a3
    mf = []
    for i in range(300):
        loss = rng.standard_normal(t3)
        r = m.mcneil_frey_residual_test(loss, np.full(t3, z3), np.full(t3, es3), np.ones(t3), a3, n_boot=499, seed=i)
        mf.append(r.p_value <= 0.05)
    # the percentile bootstrap of a skewed mean is not exactly nominal: a documented band of [0.02, 0.095]
    assert 0.02 <= rate(mf) <= 0.095, rate(mf)


def test_kupiec_at_250_days_is_discrete():
    """At T = 250 and p = 0.01 the expected count is 2.5: the asymptotic chi-square size is not 5 percent (the reason
    the exact binomial p-value is reported next to it), while the exact test is conservative."""
    n, p = 250, 0.01
    pmf = stats.binom.pmf(np.arange(n + 1), n, p)
    asym = 0.0
    exact = 0.0
    for x in range(n + 1):
        hits = np.zeros(n, dtype=bool)
        hits[:x] = True
        r = m.kupiec_pof(hits, p)
        if r.p_value < 0.05:
            asym += pmf[x]
        if r.metric < 0.05:
            exact += pmf[x]
    assert asym > 0.075 and abs(asym - 0.05) > 0.025  # about 0.12: x = 0 and x >= 6 reject
    assert exact <= 0.05 + 1e-12
    assert frtb.binomial_cumulative_probability(0, n, p) == pytest.approx(0.0811, abs=5e-4)
